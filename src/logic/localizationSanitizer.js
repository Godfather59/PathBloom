function normalizeText(value) {
  return String(value ?? '')
    .replace(/\s+AR\s*$/i, '')
    .replace(/\s+AR(?=[.!?،؛:]?$)/i, '')
    .trim();
}

function hasArabic(value) {
  return /[\u0600-\u06FF]/.test(String(value ?? ''));
}

function hasLatin(value) {
  return /[A-Za-z]/.test(String(value ?? ''));
}

function normalizeComparable(value) {
  return normalizeText(value).replace(/\s+/g, ' ').trim();
}

export function cleanLocalizedText(localizedValue, fallbackValue = '', language = 'en') {
  const localized = normalizeText(localizedValue);

  if (language !== 'ar') {
    return localized;
  }

  const fallback = normalizeText(fallbackValue);
  const fallbackKey = normalizeComparable(fallback);
  const localizedKey = normalizeComparable(localized);

  if (fallbackKey && AR_TEXT_OVERRIDES[fallbackKey]) {
    const wasPlaceholderArabic = /\s+AR\s*$/i.test(String(localizedValue ?? ''));
    const sameAsFallback = localizedKey === fallbackKey;
    if (wasPlaceholderArabic || sameAsFallback || hasLatin(localized)) {
      return AR_TEXT_OVERRIDES[fallbackKey];
    }
  }

  if (AR_TEXT_OVERRIDES[localizedKey]) {
    return AR_TEXT_OVERRIDES[localizedKey];
  }

  // Some generated events use an Arabic prefix but keep an English sentence after it.
  // If the sentence is still mostly English, prefer an Arabic fallback when available.
  if (!hasArabic(localized) && hasLatin(localized) && AR_TEXT_OVERRIDES[fallbackKey]) {
    return AR_TEXT_OVERRIDES[fallbackKey];
  }

  return localized;
}
