export function checkAchievements(person, unlockedIds) {
  if (!person || typeof person !== 'object') {
    return [];
  }

  unlockedIds = Array.isArray(unlockedIds) ? unlockedIds : [];
  const newUnlocks = [];
  const history = Array.isArray(person.history) ? person.history : [];
  const historyText = history.map(entry => String(entry?.text || '').toLowerCase());
  const hasHistory = (...needles) =>
    historyText.some(text => needles.some(needle => text.includes(needle)));
  const countHistory = needle => historyText.filter(text => text.includes(needle)).length;
  const degrees = Array.isArray(person.degrees) ? person.degrees : [];
  const educationHistory = Array.isArray(person.educationHistory) ? person.educationHistory : [];
  const graduateSchools = ['medical school', 'law school', 'business school', 'graduate school'];
  const hasGraduateDegree =
    degrees.some(degree => {
      const value = `${degree?.name || ''} ${degree?.type || ''}`.toLowerCase();
      return graduateSchools.some(school => value.includes(school)) || value.includes('phd');
    }) ||
    educationHistory.some(entry => {
      const value = String(entry || '').toLowerCase();
      return graduateSchools.some(school => value.includes(school)) || value.includes('phd');
    });
  const jobTitle = String(person.job?.title || '');
  const jobTitleLower = jobTitle.toLowerCase();

  let netWorth;
  if (typeof person.getTotalEstateValue === 'function') {
    try {
      netWorth = Number(person.getTotalEstateValue());
    } catch {
      netWorth = undefined;
    }
  }
  if (!Number.isFinite(netWorth)) {
    netWorth = Number(person.money) || 0;
    (Array.isArray(person.assets) ? person.assets : []).forEach(asset => {
      netWorth += Number(asset?.value ?? asset?.price) || 0;
      if (asset?.isMortgaged) {
        netWorth -= Math.max(0, Number(asset?.mortgage?.balance) || 0);
      }
    });
    (Array.isArray(person.portfolio) ? person.portfolio : []).forEach(position => {
      netWorth += Number(position?.currentValue) || 0;
    });
    netWorth -= Math.max(0, Number(person.loans) || 0);
    netWorth = Math.max(0, netWorth);
  }

  // Age
  if (person.age >= 50 && !unlockedIds.includes('survivor')) {
    newUnlocks.push('survivor');
  }
  if (person.age >= 70 && !unlockedIds.includes('elder')) {
    newUnlocks.push('elder');
  }
  if (person.age >= 100 && !unlockedIds.includes('centenarian')) {
    newUnlocks.push('centenarian');
  }
  if (person.age >= 110 && !unlockedIds.includes('supercentenarian')) {
    newUnlocks.push('supercentenarian');
  }

  // Wealth
  if (netWorth >= 1000000 && !unlockedIds.includes('millionaire')) {
    newUnlocks.push('millionaire');
  }
  if (netWorth >= 10000000 && !unlockedIds.includes('multi_millionaire')) {
    newUnlocks.push('multi_millionaire');
  }
  if (netWorth >= 1000000000 && !unlockedIds.includes('billionaire')) {
    newUnlocks.push('billionaire');
  }

  // Crime
  if (person.isInPrison && !unlockedIds.includes('criminal')) {
    newUnlocks.push('criminal');
  }
  if (hasHistory('successfully committed burglary') && !unlockedIds.includes('thief')) {
    newUnlocks.push('thief');
  }
  const burglaryCount = countHistory('successfully committed burglary');
  if (burglaryCount >= 10 && !unlockedIds.includes('master_thief')) {
    newUnlocks.push('master_thief');
  }
  if (
    hasHistory('successfully committed system hacking', 'successfully hacked') &&
    !unlockedIds.includes('hacker')
  ) {
    newUnlocks.push('hacker');
  }
  if (
    hasHistory('escaped prison', 'escaped from prison') &&
    !unlockedIds.includes('prison_escape')
  ) {
    newUnlocks.push('prison_escape');
  }

  // Education
  if (
    (degrees.length > 0 ||
      educationHistory.some(entry => /university|bachelor/i.test(String(entry)))) &&
    !unlockedIds.includes('educated')
  ) {
    newUnlocks.push('educated');
  }
  if (
    hasHistory('graduated high school') &&
    person.smarts >= 90 &&
    !unlockedIds.includes('valedictorian')
  ) {
    newUnlocks.push('valedictorian');
  }
  const degreeCount = degrees.length;
  if (degreeCount >= 2 && !unlockedIds.includes('double_major')) {
    newUnlocks.push('double_major');
  }
  if (degreeCount >= 3 && hasGraduateDegree && !unlockedIds.includes('polymath')) {
    newUnlocks.push('polymath');
  }

  // Career
  if (jobTitle === 'Brain Surgeon' && !unlockedIds.includes('doctor')) {
    newUnlocks.push('doctor');
  }
  if (
    (jobTitle.includes('CEO') || jobTitle === 'Chief Executive Officer') &&
    !unlockedIds.includes('top_ceo')
  ) {
    newUnlocks.push('top_ceo');
  }
  if (
    ((Number(person.spaceProgram?.missionsCompleted) || 0) > 0 ||
      hasHistory('mission complete:', 'space mission successful')) &&
    !unlockedIds.includes('astronaut')
  ) {
    newUnlocks.push('astronaut');
  }
  if ((person.companies || []).length > 0 && !unlockedIds.includes('entrepreneur')) {
    newUnlocks.push('entrepreneur');
  }
  const jobCount = new Set(historyText.filter(text => text.includes('started working as'))).size;
  if (jobCount >= 5 && !unlockedIds.includes('career_changer')) {
    newUnlocks.push('career_changer');
  }
  if ((person.isRetired || person.job?.isRetired) && !unlockedIds.includes('retired')) {
    newUnlocks.push('retired');
  }
  if (jobTitleLower.includes('firefighter') && !unlockedIds.includes('firefighter')) {
    newUnlocks.push('firefighter');
  }

  // Politics
  if (person.isHeadOfState && !unlockedIds.includes('politician')) {
    newUnlocks.push('politician');
  }
  if (jobTitle === 'Judge' && !unlockedIds.includes('judge')) {
    newUnlocks.push('judge');
  }

  // Social / Relationships
  const partners = countHistory('started dating');
  if (partners >= 5 && !unlockedIds.includes('casanova')) {
    newUnlocks.push('casanova');
  }
  const breakups = historyText.filter(
    text => text.includes('you broke up with') || text.includes('broke up with you')
  ).length;
  if (breakups >= 5 && !unlockedIds.includes('heartbreaker')) {
    newUnlocks.push('heartbreaker');
  }
  const children = (person.relationships || []).filter(r => r.type === 'Child').length;
  if (children >= 3 && !unlockedIds.includes('fertile')) {
    newUnlocks.push('fertile');
  }
  if (children >= 6 && !unlockedIds.includes('super_parent')) {
    newUnlocks.push('super_parent');
  }

  const highFriend = (person.relationships || []).find(
    r => r.type === 'Friend' && (r.stat || 0) >= 95 && (r.yearsKnown || 0) >= 20
  );
  if (highFriend && !unlockedIds.includes('best_friend')) {
    newUnlocks.push('best_friend');
  }

  // Pets
  const petCount = (person.pets || []).length;
  if (petCount >= 3 && !unlockedIds.includes('pet_lover')) {
    newUnlocks.push('pet_lover');
  }

  // Royalty
  if (person.royalty) {
    if (
      (person.history || []).some(
        h => h.text.includes('born a Prince') || h.text.includes('born a Princess')
      ) &&
      !unlockedIds.includes('born_royal')
    ) {
      newUnlocks.push('born_royal');
    }
    if (
      (person.royalty.title === 'King' || person.royalty.title === 'Queen') &&
      !unlockedIds.includes('monarch')
    ) {
      newUnlocks.push('monarch');
    }
    if (
      (person.history || []).some(h => h.text.includes('executed')) &&
      !unlockedIds.includes('tyrant')
    ) {
      newUnlocks.push('tyrant');
    }
    if (
      (person.history || []).some(
        h => h.text.includes('married into') || h.text.includes('joined the royal family')
      )
    ) {
      if (!unlockedIds.includes('royal_marriage')) {
        newUnlocks.push('royal_marriage');
      }
    }
  }

  // Military
  if (person.job && person.job.isMilitary) {
    if (
      (person.job.title.includes('General') || person.job.title.includes('Admiral')) &&
      !unlockedIds.includes('general')
    ) {
      newUnlocks.push('general');
    }
  }
  if (hasHistory('survived the minefield') && !unlockedIds.includes('war_hero')) {
    newUnlocks.push('war_hero');
  }

  // Mafia
  if (person.mafia?.family && person.mafia?.rank) {
    if (!unlockedIds.includes('made_man')) {
      newUnlocks.push('made_man');
    }
    if (
      String(person.mafia.rank).toLowerCase() === 'godfather' &&
      !unlockedIds.includes('godfather')
    ) {
      newUnlocks.push('godfather');
    }
    if (String(person.mafia.rank).toLowerCase() === 'caporegime' && !unlockedIds.includes('capo')) {
      newUnlocks.push('capo');
    }
  }

  // Education pt2
  if (hasGraduateDegree && !unlockedIds.includes('phd')) {
    newUnlocks.push('phd');
  }

  // Health / Fitness
  if (hasHistory('completed a marathon') && !unlockedIds.includes('marathon')) {
    newUnlocks.push('marathon');
  }
  const fitnessObj = person.fitness || {};
  if ((fitnessObj.muscleMass || 0) >= 50 && !unlockedIds.includes('body_builder')) {
    newUnlocks.push('body_builder');
  }

  // Lifestyle
  if (hasHistory('won the lottery') && !unlockedIds.includes('lottery')) {
    newUnlocks.push('lottery');
  }
  if (person.fame >= 95 && !unlockedIds.includes('celebrity')) {
    newUnlocks.push('celebrity');
  }
  if (
    (jobTitleLower.includes('influencer') || jobTitleLower.includes('social media')) &&
    !unlockedIds.includes('influencer')
  ) {
    newUnlocks.push('influencer');
  }
  if ((person.countriesVisited || []).length >= 10 && !unlockedIds.includes('world_traveler')) {
    newUnlocks.push('world_traveler');
  }
  if ((person.totalDonated || 0) >= 1000000 && !unlockedIds.includes('philanthropist')) {
    newUnlocks.push('philanthropist');
  }

  // Special
  const committedCrime =
    (Number(person.lifeStats?.crimesCommitted) || 0) > 0 ||
    hasHistory('successfully committed', 'caught attempting', 'were arrested');
  if (
    !person.isAlive &&
    person.karma >= 90 &&
    !person.isInPrison &&
    !committedCrime &&
    !unlockedIds.includes('immaculate')
  ) {
    newUnlocks.push('immaculate');
  }
  if (hasHistory('wrote a book') && !unlockedIds.includes('author')) {
    newUnlocks.push('author');
  }
  if (
    (jobTitleLower.includes('musician') || jobTitleLower.includes('singer')) &&
    !unlockedIds.includes('musician')
  ) {
    newUnlocks.push('musician');
  }
  if (
    (jobTitleLower.includes('athlete') ||
      jobTitleLower.includes('sports') ||
      person.job?.category === 'Sports') &&
    !unlockedIds.includes('athlete')
  ) {
    newUnlocks.push('athlete');
  }
  if (person.hasNobelPrize && !unlockedIds.includes('nobel_winner')) {
    newUnlocks.push('nobel_winner');
  }
  if ((person.patents || []).length > 0 && !unlockedIds.includes('patent_holder')) {
    newUnlocks.push('patent_holder');
  }
  if ((person.assets || []).length >= 20 && !unlockedIds.includes('hoarder')) {
    newUnlocks.push('hoarder');
  }

  // Dynasty
  const familyTree =
    person.familyTree || (typeof window !== 'undefined' ? window.__familyTree : null);
  const genCount = familyTree?.getGenerationCount ? familyTree.getGenerationCount() : 0;
  if (genCount >= 3 && !unlockedIds.includes('legacy')) {
    newUnlocks.push('legacy');
  }

  // Skills / Hobbies
  const hasDegree =
    degreeCount > 0 || educationHistory.some(entry => /university|bachelor/i.test(String(entry)));
  const hasMilitary = person.job?.isMilitary || hasHistory('military');
  const hasBusiness = (person.companies || []).length > 0 || jobTitle.includes('CEO');
  if (hasDegree && hasMilitary && hasBusiness && !unlockedIds.includes('renaissance')) {
    newUnlocks.push('renaissance');
  }

  // Cross-life
  let totalLives = 0;
  try {
    const storedLives = Number.parseInt(localStorage.getItem('bitlife_total_lives') || '0', 10);
    totalLives = Number.isFinite(storedLives) ? storedLives : 0;
  } catch {
    /* cross-life achievements are optional when storage is unavailable */
  }
  if (totalLives >= 5 && !unlockedIds.includes('reincarnation')) {
    newUnlocks.push('reincarnation');
  }

  // Speedrun - count how many achievements unlocked before age 25
  if (person.age <= 25) {
    const countBefore25 = unlockedIds.length + newUnlocks.length;
    if (countBefore25 >= 5 && !unlockedIds.includes('speedrun')) {
      newUnlocks.push('speedrun');
    }
  }

  return newUnlocks;
}
