export function translateDeepSimulationText(value, language = 'en') {
  if (language !== 'ar' || value === null || value === undefined) {
    return value;
  }
  const text = String(value).trim();
  if (AR_EXACT[text]) {
    return AR_EXACT[text];
  }
  for (const [pattern, replacer] of AR_PATTERNS) {
    const match = text.match(pattern);
    if (match) {
      return replacer(match);
    }
  }
  return value;
}
